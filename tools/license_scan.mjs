// Transitive licence scan from package-lock.json + node_modules/*/package.json (offline).
// Production deps must be on the permissive allow-list or the scan fails (exit 2).
// Usage: node tools/license_scan.mjs [--write]   (--write refreshes docs/LICENSE_SCAN.md)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ALLOW = ['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'CC0-1.0', 'BlueOak-1.0.0', 'Unlicense', 'Python-2.0', 'CC-BY-4.0'];
const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));

function licenseOf(path, meta) {
  let l = meta.license;
  if (!l && existsSync(`${path}/package.json`)) { const p = JSON.parse(readFileSync(`${path}/package.json`, 'utf8')); l = p.license ?? p.licenses?.map((x) => x.type).join(' OR '); }
  if (l && typeof l === 'object') l = l.type;
  return l ?? 'UNKNOWN';
}
/** An SPDX expression is acceptable when every AND-term has at least one allowed OR-alternative. */
export function acceptable(expr) {
  const flat = expr.replace(/[()]/g, ' ');
  return flat.split(/\s+AND\s+/).every((term) => term.split(/\s+OR\s+/).some((alt) => ALLOW.includes(alt.trim())));
}

const rows = [];
for (const [path, meta] of Object.entries(lock.packages)) {
  if (!path) continue;
  const name = path.replace(/^.*node_modules\//, '');
  rows.push({ name, version: meta.version, license: licenseOf(path, meta), dev: !!meta.dev, optional: !!meta.optional });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const prod = rows.filter((r) => !r.dev);
const bad = prod.filter((r) => !acceptable(r.license));
const devOdd = rows.filter((r) => r.dev && !acceptable(r.license));

const count = (rs) => Object.entries(rs.reduce((m, r) => ((m[r.license] = (m[r.license] ?? 0) + 1), m), {})).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k}: ${v}`).join(', ');
const md = `# Transitive licence scan
Generated by \`node tools/license_scan.mjs --write\` from \`package-lock.json\` and each installed package's \`package.json\` (offline; no network).

- Production (shipped) packages: **${prod.length}** — ${count(prod)}
- Dev-only packages (not shipped): **${rows.length - prod.length}** — ${count(rows.filter((r) => r.dev))}
- Allow-list for shipped code: ${ALLOW.join(', ')}
- Shipped packages outside the allow-list: **${bad.length}**${bad.length ? '\n' + bad.map((r) => `  - ${r.name}@${r.version}: ${r.license}`).join('\n') : ''}
- Dev-only packages outside the allow-list (review, they are build tools and are not distributed): **${devOdd.length}**${devOdd.length ? '\n' + devOdd.map((r) => `  - ${r.name}@${r.version}: ${r.license}`).join('\n') : ''}

Limits: this reads the licence *declared* in package metadata. It does not inspect LICENSE file text, bundled third-party snippets, or assets (see ASSET_LICENSE_AUDIT.md for art/audio). A lawyer's review is still advised before a paid release.

## Shipped packages
| Package | Version | Licence |
|---|---|---|
${prod.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n')}
`;
if (process.argv.includes('--write')) writeFileSync('docs/LICENSE_SCAN.md', md);
console.log(`licence scan: ${prod.length} shipped, ${rows.length - prod.length} dev; shipped outside allow-list: ${bad.length}; dev odd: ${devOdd.length}`);
for (const r of bad) console.log(`  BAD ${r.name}@${r.version}: ${r.license}`);
for (const r of devOdd) console.log(`  dev ${r.name}@${r.version}: ${r.license}`);
if (bad.length) process.exit(2);
